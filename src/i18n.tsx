export type Key = keyof Dict
const dicts: Record<Lang, Dict> = { en, ar, zh }

export interface I18n { lang: Lang; t: (k: Key) => string; setLang: (l: Lang) => void }
export const I18nCtx = createContext<I18n>(null as unknown as I18n)
export const useI18n = () => useContext(I18nCtx)
export const makeT = (lang: Lang) => (k: Key) => dicts[lang][k] ?? en[k]
export const isRtl = (l: Lang) => l === 'ar'
